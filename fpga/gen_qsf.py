#!/usr/bin/env python3
"""Generate fpga/attention_accel.qsf from rtl/filelist.txt and the top-level ports.

Kept as a generator because the design has ~790 ports that must each be declared
a virtual pin, and because the RTL list must not drift from the other flows.
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEVICE, FAMILY = "EP4CGX150DF31I7AD", "Cyclone IV GX"

# Real pins. Everything else on the top level becomes a virtual pin.
REAL = {"clk", "clk2", "reset"}

# (name, width) for every top-level port; width 0 means scalar.
PORTS = [
    ("mem_in_1", 64), ("mem_in_2", 64), ("inst", 20), ("skip_thresh", 24),
    ("pmem_out_1", 160), ("pmem_out_2", 160),
    ("sfp_out_1", 160), ("sfp_out_2", 160),
    ("div_done_1", 0), ("div_done_2", 0),
]

def rtl_files():
    out = []
    for line in (ROOT / "rtl" / "filelist.txt").read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            out.append(line)
    return out

def main():
    vp = []
    for name, width in PORTS:
        if name in REAL:
            continue
        vp += [f"{name}[{i}]" for i in range(width)] if width else [name]

    L = ["# Generated by fpga/gen_qsf.py -- edit that, not this file.", ""]
    L += [f'set_global_assignment -name FAMILY "{FAMILY}"',
          f"set_global_assignment -name DEVICE {DEVICE}",
          "set_global_assignment -name TOP_LEVEL_ENTITY fullchip",
          "set_global_assignment -name ORIGINAL_QUARTUS_VERSION 24.1",
          "set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output_files",
          ""]
    L.append("# RTL, from rtl/filelist.txt. All plain Verilog-2005: the packed")
    L.append("# multi-dimensional array that previously forced SystemVerilog in")
    L.append("# sfp_row.v has been removed.")
    for f in rtl_files():
        L.append(f"set_global_assignment -name VERILOG_FILE ../rtl/{f}")
    L += ["", "set_global_assignment -name SDC_FILE attention_accel.sdc", ""]

    L += ["# --- Power analysis ------------------------------------------------------",
          "# The VCD is passed on the quartus_pow command line by run_quartus.sh:",
          "#   quartus_pow <proj> --input_vcd=<file> --vcd_filter_glitches=on",
          "# POWER_USE_INPUT_FILE accepts only \"No File\"/\"Signal Activity File\"/",
          "# \"VCD File\" and POWER_INPUT_FILE_NAME requires a section id, so the",
          "# command line is the simpler route for a plain path.",
          "set_global_assignment -name POWER_REPORT_SIGNAL_ACTIVITY ON",
          "set_global_assignment -name POWER_REPORT_POWER_DISSIPATION ON",
          'set_global_assignment -name POWER_DEFAULT_INPUT_IO_TOGGLE_RATE "12.5 %"',
          ""]
    L += ["# --- Synthesis -----------------------------------------------------------",
          "set_global_assignment -name OPTIMIZATION_TECHNIQUE AREA",
          "set_global_assignment -name AUTO_RESOURCE_SHARING ON",
          "# Clock-enable inference is the FPGA equivalent of an integrated clock",
          "# gating cell; mac_col.v expresses its gating as a register enable so",
          "# that this can pick it up.",
          "set_global_assignment -name AUTO_CLOCK_ENABLE_RECOGNITION ON",
          "# Allow the 16-entry memories in sram_w16.v to map to M9K.",
          "set_global_assignment -name AUTO_RAM_RECOGNITION ON",
          ""]
    L += [f"# --- Virtual pins ({len(vp)}) ------------------------------------------",
          "# Only clk, clk2 and reset are real; the core's remaining ports exceed",
          "# any package pin count."]
    L += [f'set_instance_assignment -name VIRTUAL_PIN ON -to "{p}"' for p in vp]

    (ROOT / "fpga" / "attention_accel.qsf").write_text("\n".join(L) + "\n")
    print(f"wrote attention_accel.qsf: {len(rtl_files())} RTL files, {len(vp)} virtual pins")

if __name__ == "__main__":
    sys.exit(main())
